"""
IMU confidence and combined sensor confidence estimation for KITTI Raw drives.

This module applies the IMU confidence formula and Sensor Confidence Index (SCI)
from Notebook 08 to the combined sensor-quality dataframe.
"""

from __future__ import annotations

import argparse
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

import matplotlib.pyplot as plt
import pandas as pd

try:
    from .camera_quality import DEFAULT_DRIVES
    from .gps_confidence import GPSConfidenceProcessor, GPSConfidenceConfig
    from .imu_quality import IMU_QUALITY_COLUMNS
except ImportError:  # pragma: no cover - supports direct script execution.
    from camera_quality import DEFAULT_DRIVES
    from gps_confidence import GPSConfidenceProcessor, GPSConfidenceConfig
    from imu_quality import IMU_QUALITY_COLUMNS


LOGGER = logging.getLogger(__name__)


IMU_CONFIDENCE_WEIGHTS: dict[str, float] = {
    "Motion Smoothness": 0.50,
    "Angular Stability": 0.50,
}


@dataclass(frozen=True)
class IMUConfidenceConfig:
    """Configuration for IMU and combined sensor-confidence processing."""

    results_dir: Path
    figures_dir: Path
    save_figures: bool = True


@dataclass(frozen=True)
class IMUConfidenceArtifacts:
    """Paths generated by an IMU-confidence processing run."""

    imu_confidence_csv: Path
    sensor_confidence_csv: Path
    sensor_confidence_statistics_csv: Path
    sensor_confidence_summary_csv: Path
    figure: Path | None


class IMUConfidenceError(RuntimeError):
    """Raised when IMU-confidence processing cannot complete safely."""


class IMUConfidenceProcessor:
    """Compute notebook-compatible IMU confidence and SCI."""

    def __init__(
        self,
        config: IMUConfidenceConfig,
        logger: logging.Logger | None = None,
    ) -> None:
        self.config = config
        self.logger = logger or LOGGER

    def process_drive(self, drive: str) -> tuple[pd.DataFrame, IMUConfidenceArtifacts]:
        """Compute IMU confidence and Sensor Confidence Index for one drive."""

        sensor_quality_csv = (
            self.config.results_dir / f"sensor_quality_metrics_{drive}.csv"
        )
        if not sensor_quality_csv.exists():
            raise IMUConfidenceError(
                f"Sensor quality CSV is required before IMU confidence: {sensor_quality_csv}"
            )

        quality_df = pd.read_csv(sensor_quality_csv)
        if "GPS Confidence" not in quality_df.columns:
            self.logger.info(
                "GPS Confidence missing for %s; running GPS confidence stage first.",
                drive,
            )
            gps_config = GPSConfidenceConfig(
                results_dir=self.config.results_dir,
                figures_dir=self.config.figures_dir,
                save_figures=False,
            )
            gps_processor = GPSConfidenceProcessor(gps_config, logger=self.logger)
            quality_df, _ = gps_processor.process_drive(drive)

        confidence_df = self.compute_confidence(quality_df)
        artifacts = self._export_drive_outputs(drive, confidence_df)
        self.logger.info(
            "Completed IMU/SCI confidence for %s: %s frames -> %s",
            drive,
            len(confidence_df),
            artifacts.sensor_confidence_csv,
        )
        return confidence_df, artifacts

    def process_drives(
        self,
        drives: Sequence[str] | None = None,
    ) -> dict[str, IMUConfidenceArtifacts]:
        """Process multiple drives and return artifact paths keyed by drive."""

        selected_drives = tuple(drives or DEFAULT_DRIVES)
        if not selected_drives:
            raise IMUConfidenceError("At least one drive must be provided.")

        artifacts_by_drive: dict[str, IMUConfidenceArtifacts] = {}
        for drive in selected_drives:
            _, artifacts = self.process_drive(drive)
            artifacts_by_drive[drive] = artifacts
        return artifacts_by_drive

    def compute_confidence(self, quality_df: pd.DataFrame) -> pd.DataFrame:
        """Apply Notebook 08 IMU confidence and SCI formulas."""

        self._validate_quality_dataframe(quality_df)
        confidence_df = quality_df.copy()
        confidence_df["IMU Confidence"] = sum(
            IMU_CONFIDENCE_WEIGHTS[column] * confidence_df[column]
            for column in IMU_CONFIDENCE_WEIGHTS
        )
        confidence_df["Sensor Confidence Index"] = (
            0.60 * confidence_df["GPS Confidence"]
            + 0.40 * confidence_df["IMU Confidence"]
        )
        confidence_df["Confidence Level"] = confidence_df[
            "Sensor Confidence Index"
        ].apply(self.classify)
        return confidence_df

    @staticmethod
    def classify(score: float) -> str:
        """Classify a confidence score using the notebook thresholds."""

        if score >= 0.90:
            return "Excellent"
        if score >= 0.75:
            return "High"
        if score >= 0.60:
            return "Moderate"
        if score >= 0.40:
            return "Low"
        return "Poor"

    def _validate_quality_dataframe(self, quality_df: pd.DataFrame) -> None:
        required_columns = [*IMU_CONFIDENCE_WEIGHTS, "GPS Confidence"]
        missing = [column for column in required_columns if column not in quality_df.columns]
        if missing:
            raise IMUConfidenceError(f"Quality dataframe is missing columns: {missing}")
        if quality_df.empty:
            raise IMUConfidenceError("Quality dataframe contains no rows.")

    def _export_drive_outputs(
        self,
        drive: str,
        confidence_df: pd.DataFrame,
    ) -> IMUConfidenceArtifacts:
        self.config.results_dir.mkdir(parents=True, exist_ok=True)
        self.config.figures_dir.mkdir(parents=True, exist_ok=True)

        imu_confidence_csv = self.config.results_dir / f"imu_confidence_{drive}.csv"
        sensor_confidence_csv = (
            self.config.results_dir / f"sensor_confidence_index_{drive}.csv"
        )
        statistics_csv = (
            self.config.results_dir / f"sensor_confidence_statistics_{drive}.csv"
        )
        summary_csv = self.config.results_dir / f"sensor_confidence_summary_{drive}.csv"

        confidence_columns = [
            "GPS Confidence",
            "IMU Confidence",
            "Sensor Confidence Index",
            "Confidence Level",
        ]
        confidence_df[[*IMU_QUALITY_COLUMNS, "IMU Confidence"]].to_csv(
            imu_confidence_csv,
            index=False,
        )
        confidence_df.to_csv(sensor_confidence_csv, index=False)
        confidence_df[confidence_columns[:-1]].describe().to_csv(statistics_csv)
        self._build_summary(confidence_df).to_csv(summary_csv, index=False)

        figure: Path | None = None
        if self.config.save_figures:
            figure = self.config.figures_dir / f"sensor_confidence_evolution_{drive}.png"
            self._save_figure(confidence_df, figure, drive)

        return IMUConfidenceArtifacts(
            imu_confidence_csv=imu_confidence_csv,
            sensor_confidence_csv=sensor_confidence_csv,
            sensor_confidence_statistics_csv=statistics_csv,
            sensor_confidence_summary_csv=summary_csv,
            figure=figure,
        )

    def _build_summary(self, confidence_df: pd.DataFrame) -> pd.DataFrame:
        return pd.DataFrame(
            {
                "Metric": [
                    "Average GPS Confidence",
                    "Average IMU Confidence",
                    "Average Sensor Confidence Index",
                    "Maximum Sensor Confidence Index",
                    "Minimum Sensor Confidence Index",
                    "Sensor Confidence Index Std",
                ],
                "Value": [
                    float(confidence_df["GPS Confidence"].mean()),
                    float(confidence_df["IMU Confidence"].mean()),
                    float(confidence_df["Sensor Confidence Index"].mean()),
                    float(confidence_df["Sensor Confidence Index"].max()),
                    float(confidence_df["Sensor Confidence Index"].min()),
                    float(confidence_df["Sensor Confidence Index"].std()),
                ],
            }
        )

    def _save_figure(
        self,
        confidence_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axis = plt.subplots(figsize=(12, 5))
        axis.plot(
            confidence_df["GPS Confidence"],
            label="GPS Confidence",
            linewidth=1.6,
        )
        axis.plot(
            confidence_df["IMU Confidence"],
            label="IMU Confidence",
            linewidth=1.6,
        )
        axis.plot(
            confidence_df["Sensor Confidence Index"],
            label="Sensor Confidence Index",
            linewidth=2.0,
        )
        axis.set_title(f"Sensor Confidence Evolution - {drive}")
        axis.set_xlabel("Frame")
        axis.set_ylabel("Confidence")
        axis.set_ylim(0, 1)
        axis.grid(True, alpha=0.3)
        axis.legend()
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)


def process_imu_confidence_for_drive(
    drive: str,
    results_dir: Path | str,
    figures_dir: Path | str,
    save_figures: bool = True,
) -> pd.DataFrame:
    """Convenience API used by orchestration code for one drive."""

    config = IMUConfidenceConfig(
        results_dir=Path(results_dir),
        figures_dir=Path(figures_dir),
        save_figures=save_figures,
    )
    processor = IMUConfidenceProcessor(config)
    confidence_df, _ = processor.process_drive(drive)
    return confidence_df


def configure_logging(level: int = logging.INFO) -> None:
    """Configure console logging for script execution."""

    logging.basicConfig(
        level=level,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments for IMU-confidence processing."""

    parser = argparse.ArgumentParser(
        description="Compute IMU confidence and SCI from sensor quality CSV files."
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path(r"D:\Research\Papers\Paper_2"),
        help="Project root containing results and figures directories.",
    )
    parser.add_argument(
        "--drive",
        action="append",
        dest="drives",
        help="Drive name to process. Repeat for multiple drives.",
    )
    parser.add_argument("--no-figures", action="store_true", help="Skip figure export.")
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    """Run IMU-confidence extraction from the command line."""

    configure_logging()
    args = parse_args(argv)
    try:
        config = IMUConfidenceConfig(
            results_dir=args.project_root / "results",
            figures_dir=args.project_root / "figures",
            save_figures=not args.no_figures,
        )
        processor = IMUConfidenceProcessor(config)
        processor.process_drives(tuple(args.drives or DEFAULT_DRIVES))
    except IMUConfidenceError:
        LOGGER.exception("IMU-confidence processing failed.")
        return 1
    except Exception:
        LOGGER.exception("Unexpected IMU-confidence processing failure.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
