"""
Confidence-Driven Adaptive Fusion (CDA-EKF orchestration) for KITTI Raw drives.

This module wires the per-frame ``sensor_confidence_index_{drive}.csv``
(OXTS + GPS/IMU confidence) and ``adaptive_sensor_weights_{drive}.csv``
(Camera/GPS/IMU weights) artifacts into the CDA-EKF implemented in
``adaptive_ekf.py``, exporting a fused trajectory, a fixed-weight
baseline trajectory, and trajectory-error metrics for both, following
the same Config/Artifacts/Processor pattern used throughout the
pipeline (e.g. ``camera_quality.py``, ``adaptive_weights.py``).
"""

from __future__ import annotations

import argparse
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

try:
    from .adaptive_ekf import AdaptiveEKFConfig, AdaptiveEKFError, run_adaptive_ekf
    from .camera_quality import DEFAULT_DRIVES
    from .gps_quality import OXTS_COLUMNS
except ImportError:  # pragma: no cover - supports direct script execution.
    from adaptive_ekf import AdaptiveEKFConfig, AdaptiveEKFError, run_adaptive_ekf
    from camera_quality import DEFAULT_DRIVES
    from gps_quality import OXTS_COLUMNS


LOGGER = logging.getLogger(__name__)


@dataclass(frozen=True)
class AdaptiveFusionConfig:
    """Configuration for CDA-EKF fusion processing."""

    results_dir: Path
    figures_dir: Path
    ekf_config: AdaptiveEKFConfig | None = None
    save_figures: bool = True


@dataclass(frozen=True)
class AdaptiveFusionArtifacts:
    """Paths generated by an adaptive-fusion processing run."""

    trajectory_csv: Path
    error_metrics_csv: Path
    summary_csv: Path
    trajectory_figure: Path | None
    error_figure: Path | None


class AdaptiveFusionError(RuntimeError):
    """Raised when CDA-EKF fusion processing cannot complete safely."""


class AdaptiveFusionProcessor:
    """Run the CDA-EKF (adaptive) and a fixed-weight EKF (baseline)."""

    def __init__(
        self,
        config: AdaptiveFusionConfig,
        logger: logging.Logger | None = None,
    ) -> None:
        self.config = config
        self.logger = logger or LOGGER

    # ------------------------------------------------------------------
    # Single drive
    # ------------------------------------------------------------------

    def process_drive(self, drive: str) -> tuple[pd.DataFrame, AdaptiveFusionArtifacts]:
        """Fuse one KITTI Raw drive and export trajectory/error artifacts."""

        self.logger.info("Starting CDA-EKF fusion for %s", drive)
        oxts_df, weights_df = self._load_inputs(drive)

        ekf_config = self.config.ekf_config or AdaptiveEKFConfig()
        try:
            adaptive_df = run_adaptive_ekf(
                oxts_df, weights_df, config=ekf_config, adaptive=True
            )
            baseline_df = run_adaptive_ekf(
                oxts_df, weights_df, config=ekf_config, adaptive=False
            )
        except AdaptiveEKFError as exc:
            raise AdaptiveFusionError(f"CDA-EKF failed for {drive}: {exc}") from exc

        merged_df = self._merge_trajectories(adaptive_df, baseline_df)
        fusion_df, error_df = self._compute_error_metrics(merged_df)
        artifacts = self._export_drive_outputs(drive, fusion_df, error_df)

        self.logger.info(
            "Completed CDA-EKF fusion for %s: %s frames -> %s",
            drive,
            len(fusion_df),
            artifacts.trajectory_csv,
        )
        return fusion_df, artifacts

    def process_drives(
        self,
        drives: Sequence[str] | None = None,
    ) -> dict[str, AdaptiveFusionArtifacts]:
        """Process multiple drives and return artifact paths keyed by drive."""

        selected_drives = tuple(drives or DEFAULT_DRIVES)
        if not selected_drives:
            raise AdaptiveFusionError("At least one drive must be provided.")

        artifacts_by_drive: dict[str, AdaptiveFusionArtifacts] = {}
        for drive in selected_drives:
            _, artifacts = self.process_drive(drive)
            artifacts_by_drive[drive] = artifacts
        return artifacts_by_drive

    # ------------------------------------------------------------------
    # Loading / validation
    # ------------------------------------------------------------------

    def _load_inputs(self, drive: str) -> tuple[pd.DataFrame, pd.DataFrame]:
        confidence_csv = self.config.results_dir / f"sensor_confidence_index_{drive}.csv"
        weights_csv = self.config.results_dir / f"adaptive_sensor_weights_{drive}.csv"

        if not confidence_csv.exists():
            raise AdaptiveFusionError(
                f"Sensor confidence index CSV is required before fusion: {confidence_csv}"
            )
        if not weights_csv.exists():
            raise AdaptiveFusionError(
                f"Adaptive sensor weights CSV is required before fusion: {weights_csv}"
            )

        confidence_df = pd.read_csv(confidence_csv)
        missing_oxts = [c for c in OXTS_COLUMNS if c not in confidence_df.columns]
        if missing_oxts:
            raise AdaptiveFusionError(
                f"Sensor confidence index CSV is missing OXTS columns: {missing_oxts}"
            )
        oxts_df = confidence_df[list(OXTS_COLUMNS)].reset_index(drop=True)

        weights_df = pd.read_csv(weights_csv)
        required_weight_columns = {"Frame", "Camera Weight", "GPS Weight", "IMU Weight"}
        missing_weights = required_weight_columns.difference(weights_df.columns)
        if missing_weights:
            raise AdaptiveFusionError(
                f"Adaptive sensor weights CSV is missing columns: {missing_weights}"
            )

        if len(oxts_df) != len(weights_df):
            raise AdaptiveFusionError(
                f"Frame count mismatch for {drive}: OXTS={len(oxts_df)}, "
                f"weights={len(weights_df)}"
            )

        return oxts_df, weights_df

    # ------------------------------------------------------------------
    # Computation
    # ------------------------------------------------------------------

    def _merge_trajectories(
        self,
        adaptive_df: pd.DataFrame,
        baseline_df: pd.DataFrame,
    ) -> pd.DataFrame:
        merged = adaptive_df.merge(
            baseline_df,
            on=["Frame", "X GPS", "Y GPS", "V GPS"],
            suffixes=(" Adaptive", " Baseline"),
        )
        return merged

    def _compute_error_metrics(
        self, fusion_df: pd.DataFrame
    ) -> tuple[pd.DataFrame, pd.DataFrame]:
        """Position RMSE / mean absolute error against the GPS reference track."""

        def _position_errors(x_col: str, y_col: str) -> np.ndarray:
            dx = fusion_df[x_col].to_numpy(dtype=float) - fusion_df["X GPS"].to_numpy(dtype=float)
            dy = fusion_df[y_col].to_numpy(dtype=float) - fusion_df["Y GPS"].to_numpy(dtype=float)
            return np.sqrt(dx**2 + dy**2)

        adaptive_errors = _position_errors("X Adaptive", "Y Adaptive")
        baseline_errors = _position_errors("X Baseline", "Y Baseline")

        adaptive_rmse = float(np.sqrt(np.mean(adaptive_errors**2)))
        baseline_rmse = float(np.sqrt(np.mean(baseline_errors**2)))
        adaptive_mae = float(np.mean(adaptive_errors))
        baseline_mae = float(np.mean(baseline_errors))
        adaptive_final_drift = float(adaptive_errors[-1])
        baseline_final_drift = float(baseline_errors[-1])

        improvement_pct = (
            0.0
            if baseline_rmse <= 1e-12
            else float(100.0 * (baseline_rmse - adaptive_rmse) / baseline_rmse)
        )

        fusion_df = fusion_df.copy()
        fusion_df["Adaptive Position Error (m)"] = adaptive_errors
        fusion_df["Baseline Position Error (m)"] = baseline_errors

        error_df = pd.DataFrame(
            {
                "Metric": [
                    "Adaptive RMSE (m)",
                    "Baseline RMSE (m)",
                    "Adaptive MAE (m)",
                    "Baseline MAE (m)",
                    "Adaptive Final Drift (m)",
                    "Baseline Final Drift (m)",
                    "RMSE Improvement (%)",
                ],
                "Value": [
                    adaptive_rmse,
                    baseline_rmse,
                    adaptive_mae,
                    baseline_mae,
                    adaptive_final_drift,
                    baseline_final_drift,
                    improvement_pct,
                ],
            }
        )
        return fusion_df, error_df

    # ------------------------------------------------------------------
    # Export
    # ------------------------------------------------------------------

    def _export_drive_outputs(
        self,
        drive: str,
        fusion_df: pd.DataFrame,
        error_df: pd.DataFrame,
    ) -> AdaptiveFusionArtifacts:
        self.config.results_dir.mkdir(parents=True, exist_ok=True)
        self.config.figures_dir.mkdir(parents=True, exist_ok=True)

        trajectory_csv = self.config.results_dir / f"fusion_trajectory_{drive}.csv"
        error_metrics_csv = self.config.results_dir / f"fusion_error_metrics_{drive}.csv"
        summary_csv = self.config.results_dir / f"fusion_summary_{drive}.csv"

        fusion_df.to_csv(trajectory_csv, index=False)
        error_df.to_csv(error_metrics_csv, index=False)
        error_df.to_csv(summary_csv, index=False)

        trajectory_figure: Path | None = None
        error_figure: Path | None = None
        if self.config.save_figures:
            trajectory_figure = self.config.figures_dir / f"fusion_trajectory_{drive}.png"
            error_figure = self.config.figures_dir / f"fusion_error_{drive}.png"
            self._save_trajectory_figure(fusion_df, trajectory_figure, drive)
            self._save_error_figure(fusion_df, error_figure, drive)

        return AdaptiveFusionArtifacts(
            trajectory_csv=trajectory_csv,
            error_metrics_csv=error_metrics_csv,
            summary_csv=summary_csv,
            trajectory_figure=trajectory_figure,
            error_figure=error_figure,
        )

    def _save_trajectory_figure(
        self,
        fusion_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axis = plt.subplots(figsize=(9, 9))
        axis.plot(fusion_df["X GPS"], fusion_df["Y GPS"], label="GPS Reference", linewidth=1.4, color="tab:gray")
        axis.plot(
            fusion_df["X Baseline"],
            fusion_df["Y Baseline"],
            label="Fixed-Weight EKF (Baseline)",
            linewidth=1.6,
            linestyle="--",
            color="tab:orange",
        )
        axis.plot(
            fusion_df["X Adaptive"],
            fusion_df["Y Adaptive"],
            label="CDA-EKF (Adaptive)",
            linewidth=1.8,
            color="tab:blue",
        )
        axis.set_title(f"Fused Trajectory - {drive}")
        axis.set_xlabel("X (m)")
        axis.set_ylabel("Y (m)")
        axis.axis("equal")
        axis.grid(True, alpha=0.3)
        axis.legend()
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)

    def _save_error_figure(
        self,
        fusion_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axis = plt.subplots(figsize=(12, 5))
        axis.plot(
            fusion_df["Frame"],
            fusion_df["Baseline Position Error (m)"],
            label="Fixed-Weight EKF (Baseline)",
            linewidth=1.6,
            linestyle="--",
            color="tab:orange",
        )
        axis.plot(
            fusion_df["Frame"],
            fusion_df["Adaptive Position Error (m)"],
            label="CDA-EKF (Adaptive)",
            linewidth=1.8,
            color="tab:blue",
        )
        axis.set_title(f"Position Error vs. GPS Reference - {drive}")
        axis.set_xlabel("Frame")
        axis.set_ylabel("Position Error (m)")
        axis.grid(True, alpha=0.3)
        axis.legend()
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)


def process_adaptive_fusion_for_drive(
    drive: str,
    results_dir: Path | str,
    figures_dir: Path | str,
    save_figures: bool = True,
) -> pd.DataFrame:
    """Convenience API used by orchestration code for one drive."""

    config = AdaptiveFusionConfig(
        results_dir=Path(results_dir),
        figures_dir=Path(figures_dir),
        save_figures=save_figures,
    )
    processor = AdaptiveFusionProcessor(config)
    fusion_df, _ = processor.process_drive(drive)
    return fusion_df


def configure_logging(level: int = logging.INFO) -> None:
    """Configure console logging for script execution."""

    logging.basicConfig(
        level=level,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments for adaptive-fusion processing."""

    parser = argparse.ArgumentParser(
        description="Run the CDA-EKF and fixed-weight baseline for KITTI Raw drives."
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path(r"D:\Research\Papers\Paper_2"),
        help="Project root containing results and figures directories.",
    )
    parser.add_argument(
        "--drive",
        action="append",
        dest="drives",
        help="Drive name to process. Repeat for multiple drives.",
    )
    parser.add_argument("--no-figures", action="store_true", help="Skip figure export.")
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    """Run CDA-EKF fusion from the command line."""

    configure_logging()
    args = parse_args(argv)
    try:
        config = AdaptiveFusionConfig(
            results_dir=args.project_root / "results",
            figures_dir=args.project_root / "figures",
            save_figures=not args.no_figures,
        )
        processor = AdaptiveFusionProcessor(config)
        processor.process_drives(tuple(args.drives or DEFAULT_DRIVES))
    except AdaptiveFusionError:
        LOGGER.exception("Adaptive-fusion processing failed.")
        return 1
    except Exception:
        LOGGER.exception("Unexpected adaptive-fusion processing failure.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())