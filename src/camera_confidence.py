"""
Camera confidence estimation for KITTI Raw drives.

This module wraps the confidence-scoring algorithm from Notebook 05 and
``src.confidence_metrics`` so the pipeline can process every drive without
editing any notebook.
"""

from __future__ import annotations

import argparse
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

import matplotlib.pyplot as plt
import pandas as pd

try:
    from .camera_quality import DEFAULT_DRIVES
    from .confidence_metrics import ConfidenceMetrics
except ImportError:  # pragma: no cover - supports direct script execution.
    from camera_quality import DEFAULT_DRIVES
    from confidence_metrics import ConfidenceMetrics


LOGGER = logging.getLogger(__name__)


REQUIRED_QUALITY_COLUMNS: tuple[str, ...] = (
    "Brightness",
    "Contrast",
    "Blur",
    "Entropy",
    "Dynamic Range",
    "Edge Density",
    "Noise",
    "Frame",
)


@dataclass(frozen=True)
class CameraConfidenceConfig:
    """Configuration for camera-confidence processing."""

    results_dir: Path
    figures_dir: Path
    save_figures: bool = True


@dataclass(frozen=True)
class CameraConfidenceArtifacts:
    """Paths generated by a camera-confidence processing run."""

    confidence_csv: Path
    statistics_csv: Path
    evolution_figure: Path | None
    distribution_figure: Path | None
    level_figure: Path | None


class CameraConfidenceError(RuntimeError):
    """Raised when camera-confidence processing cannot complete safely."""


class CameraConfidenceProcessor:
    """Compute notebook-compatible camera confidence for one or more drives."""

    def __init__(
        self,
        config: CameraConfidenceConfig,
        confidence_calculator: ConfidenceMetrics | None = None,
        logger: logging.Logger | None = None,
    ) -> None:
        self.config = config
        self.confidence_calculator = confidence_calculator or ConfidenceMetrics()
        self.logger = logger or LOGGER

    def process_drive(self, drive: str) -> tuple[pd.DataFrame, CameraConfidenceArtifacts]:
        """
        Compute camera confidence for a single drive from quality metrics.

        Parameters
        ----------
        drive:
            KITTI Raw synchronized drive name.

        Returns
        -------
        tuple[pandas.DataFrame, CameraConfidenceArtifacts]
            Frame-level confidence data and paths written to disk.
        """

        quality_csv = self.config.results_dir / f"camera_quality_metrics_{drive}.csv"
        if not quality_csv.exists():
            raise CameraConfidenceError(
                f"Camera quality CSV is required before confidence estimation: {quality_csv}"
            )

        self.logger.info("Loading camera quality metrics for %s from %s", drive, quality_csv)
        quality_df = pd.read_csv(quality_csv)
        self._validate_quality_dataframe(quality_df, quality_csv)

        try:
            confidence_df = self.confidence_calculator.compute(quality_df)
        except Exception as exc:
            raise CameraConfidenceError(
                f"Failed to compute camera confidence for {drive}."
            ) from exc

        artifacts = self._export_drive_outputs(drive, confidence_df)
        self.logger.info(
            "Completed camera confidence for %s: %s frames -> %s",
            drive,
            len(confidence_df),
            artifacts.confidence_csv,
        )
        return confidence_df, artifacts

    def process_drives(
        self,
        drives: Sequence[str] | None = None,
    ) -> dict[str, CameraConfidenceArtifacts]:
        """Process multiple drives and return artifact paths keyed by drive."""

        selected_drives = tuple(drives or DEFAULT_DRIVES)
        if not selected_drives:
            raise CameraConfidenceError("At least one drive must be provided.")

        artifacts_by_drive: dict[str, CameraConfidenceArtifacts] = {}
        for drive in selected_drives:
            _, artifacts = self.process_drive(drive)
            artifacts_by_drive[drive] = artifacts
        return artifacts_by_drive

    def _validate_quality_dataframe(self, quality_df: pd.DataFrame, source: Path) -> None:
        missing = [
            column for column in REQUIRED_QUALITY_COLUMNS if column not in quality_df.columns
        ]
        if missing:
            raise CameraConfidenceError(
                f"Camera quality CSV {source} is missing columns: {missing}"
            )
        if quality_df.empty:
            raise CameraConfidenceError(f"Camera quality CSV contains no rows: {source}")

    def _export_drive_outputs(
        self,
        drive: str,
        confidence_df: pd.DataFrame,
    ) -> CameraConfidenceArtifacts:
        self.config.results_dir.mkdir(parents=True, exist_ok=True)
        self.config.figures_dir.mkdir(parents=True, exist_ok=True)

        confidence_csv = self.config.results_dir / f"camera_confidence_{drive}.csv"
        statistics_csv = (
            self.config.results_dir / f"camera_confidence_statistics_{drive}.csv"
        )
        confidence_df.to_csv(confidence_csv, index=False)
        confidence_df[["Camera Confidence"]].describe().to_csv(statistics_csv)

        evolution_figure: Path | None = None
        distribution_figure: Path | None = None
        level_figure: Path | None = None
        if self.config.save_figures:
            evolution_figure = (
                self.config.figures_dir / f"camera_confidence_evolution_{drive}.png"
            )
            distribution_figure = (
                self.config.figures_dir / f"camera_confidence_distribution_{drive}.png"
            )
            level_figure = (
                self.config.figures_dir / f"camera_confidence_levels_{drive}.png"
            )
            self._save_evolution_figure(confidence_df, evolution_figure, drive)
            self._save_distribution_figure(confidence_df, distribution_figure, drive)
            self._save_level_figure(confidence_df, level_figure, drive)

        return CameraConfidenceArtifacts(
            confidence_csv=confidence_csv,
            statistics_csv=statistics_csv,
            evolution_figure=evolution_figure,
            distribution_figure=distribution_figure,
            level_figure=level_figure,
        )

    def _save_evolution_figure(
        self,
        confidence_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axis = plt.subplots(figsize=(12, 5))
        axis.plot(
            confidence_df["Frame"],
            confidence_df["Camera Confidence"],
            color="tab:blue",
            linewidth=1.8,
            label="Camera Confidence",
        )
        axis.set_title(f"Camera Confidence Evolution - {drive}")
        axis.set_xlabel("Frame")
        axis.set_ylabel("Camera Confidence")
        axis.set_ylim(0, 1)
        axis.grid(True, alpha=0.3)
        axis.legend()
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)

    def _save_distribution_figure(
        self,
        confidence_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axis = plt.subplots(figsize=(8, 5))
        axis.hist(
            confidence_df["Camera Confidence"],
            bins=20,
            color="tab:green",
            edgecolor="black",
            alpha=0.85,
        )
        axis.set_title(f"Camera Confidence Distribution - {drive}")
        axis.set_xlabel("Camera Confidence")
        axis.set_ylabel("Frequency")
        axis.grid(True, axis="y", alpha=0.3)
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)

    def _save_level_figure(
        self,
        confidence_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        level_order = ["Poor", "Low", "Moderate", "High", "Excellent"]
        counts = confidence_df["Confidence Level"].value_counts().reindex(
            level_order,
            fill_value=0,
        )

        fig, axis = plt.subplots(figsize=(8, 5))
        axis.bar(counts.index, counts.values, color="tab:orange")
        axis.set_title(f"Camera Confidence Levels - {drive}")
        axis.set_xlabel("Confidence Level")
        axis.set_ylabel("Frame Count")
        axis.grid(True, axis="y", alpha=0.3)
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)


def process_camera_confidence_for_drive(
    drive: str,
    results_dir: Path | str,
    figures_dir: Path | str,
    save_figures: bool = True,
) -> pd.DataFrame:
    """Convenience API used by orchestration code for one drive."""

    config = CameraConfidenceConfig(
        results_dir=Path(results_dir),
        figures_dir=Path(figures_dir),
        save_figures=save_figures,
    )
    processor = CameraConfidenceProcessor(config)
    confidence_df, _ = processor.process_drive(drive)
    return confidence_df


def configure_logging(level: int = logging.INFO) -> None:
    """Configure console logging for script execution."""

    logging.basicConfig(
        level=level,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments for camera-confidence processing."""

    parser = argparse.ArgumentParser(
        description="Compute camera confidence from camera quality CSV files."
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="Project root containing results and figures directories.",
    )
    parser.add_argument(
        "--drive",
        action="append",
        dest="drives",
        help="Drive name to process. Repeat for multiple drives.",
    )
    parser.add_argument(
        "--no-figures",
        action="store_true",
        help="Skip figure export.",
    )
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    """Run camera-confidence extraction from the command line."""

    configure_logging()
    args = parse_args(argv)

    try:
        config = CameraConfidenceConfig(
            results_dir=args.project_root / "results",
            figures_dir=args.project_root / "figures",
            save_figures=not args.no_figures,
        )
        processor = CameraConfidenceProcessor(config)
        processor.process_drives(tuple(args.drives or DEFAULT_DRIVES))
    except CameraConfidenceError:
        LOGGER.exception("Camera-confidence processing failed.")
        return 1
    except Exception:
        LOGGER.exception("Unexpected camera-confidence processing failure.")
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
