"""
GPS confidence estimation for KITTI Raw drives.

This module applies the GPS weighted-confidence formula from Notebook 08 to the
per-frame GPS quality metrics generated by ``gps_quality.py``.
"""

from __future__ import annotations

import argparse
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

import matplotlib.pyplot as plt
import pandas as pd

try:
    from .camera_quality import DEFAULT_DRIVES
    from .gps_quality import GPS_QUALITY_COLUMNS
except ImportError:  # pragma: no cover - supports direct script execution.
    from camera_quality import DEFAULT_DRIVES
    from gps_quality import GPS_QUALITY_COLUMNS


LOGGER = logging.getLogger(__name__)


GPS_CONFIDENCE_WEIGHTS: dict[str, float] = {
    "GPS Position Stability": 0.20,
    "GPS Velocity Stability": 0.20,
    "GPS Heading Stability": 0.15,
    "Satellite Quality": 0.15,
    "Position Accuracy Score": 0.15,
    "Velocity Accuracy Score": 0.15,
}


@dataclass(frozen=True)
class GPSConfidenceConfig:
    """Configuration for GPS-confidence processing."""

    results_dir: Path
    figures_dir: Path
    save_figures: bool = True


@dataclass(frozen=True)
class GPSConfidenceArtifacts:
    """Paths generated by a GPS-confidence processing run."""

    gps_confidence_csv: Path
    sensor_quality_csv: Path
    statistics_csv: Path
    figure: Path | None


class GPSConfidenceError(RuntimeError):
    """Raised when GPS-confidence processing cannot complete safely."""


class GPSConfidenceProcessor:
    """Compute notebook-compatible GPS confidence for one or more drives."""

    def __init__(
        self,
        config: GPSConfidenceConfig,
        logger: logging.Logger | None = None,
    ) -> None:
        self.config = config
        self.logger = logger or LOGGER

    def process_drive(self, drive: str) -> tuple[pd.DataFrame, GPSConfidenceArtifacts]:
        """Compute GPS confidence for a single drive and export artifacts."""

        sensor_quality_csv = (
            self.config.results_dir / f"sensor_quality_metrics_{drive}.csv"
        )
        if not sensor_quality_csv.exists():
            raise GPSConfidenceError(
                f"Sensor quality CSV is required before GPS confidence: {sensor_quality_csv}"
            )

        self.logger.info("Loading sensor quality metrics for %s", drive)
        quality_df = pd.read_csv(sensor_quality_csv)
        confidence_df = self.compute_confidence(quality_df)
        artifacts = self._export_drive_outputs(drive, confidence_df)
        self.logger.info(
            "Completed GPS confidence for %s: %s frames -> %s",
            drive,
            len(confidence_df),
            artifacts.gps_confidence_csv,
        )
        return confidence_df, artifacts

    def process_drives(
        self,
        drives: Sequence[str] | None = None,
    ) -> dict[str, GPSConfidenceArtifacts]:
        """Process multiple drives and return artifact paths keyed by drive."""

        selected_drives = tuple(drives or DEFAULT_DRIVES)
        if not selected_drives:
            raise GPSConfidenceError("At least one drive must be provided.")

        artifacts_by_drive: dict[str, GPSConfidenceArtifacts] = {}
        for drive in selected_drives:
            _, artifacts = self.process_drive(drive)
            artifacts_by_drive[drive] = artifacts
        return artifacts_by_drive

    def compute_confidence(self, quality_df: pd.DataFrame) -> pd.DataFrame:
        """Apply Notebook 08 GPS confidence weights to a quality dataframe."""

        self._validate_quality_dataframe(quality_df)
        confidence_df = quality_df.copy()
        confidence_df["GPS Confidence"] = sum(
            GPS_CONFIDENCE_WEIGHTS[column] * confidence_df[column]
            for column in GPS_CONFIDENCE_WEIGHTS
        )
        return confidence_df

    def _validate_quality_dataframe(self, quality_df: pd.DataFrame) -> None:
        required_columns = tuple(GPS_CONFIDENCE_WEIGHTS)
        missing = [column for column in required_columns if column not in quality_df.columns]
        if missing:
            raise GPSConfidenceError(f"Quality dataframe is missing GPS columns: {missing}")
        if quality_df.empty:
            raise GPSConfidenceError("Quality dataframe contains no rows.")

    def _export_drive_outputs(
        self,
        drive: str,
        confidence_df: pd.DataFrame,
    ) -> GPSConfidenceArtifacts:
        self.config.results_dir.mkdir(parents=True, exist_ok=True)
        self.config.figures_dir.mkdir(parents=True, exist_ok=True)

        gps_confidence_csv = self.config.results_dir / f"gps_confidence_{drive}.csv"
        sensor_quality_csv = (
            self.config.results_dir / f"sensor_quality_metrics_{drive}.csv"
        )
        statistics_csv = self.config.results_dir / f"gps_confidence_statistics_{drive}.csv"

        columns = [*GPS_QUALITY_COLUMNS, "GPS Confidence"]
        confidence_df[columns].to_csv(gps_confidence_csv, index=False)
        confidence_df.to_csv(sensor_quality_csv, index=False)
        confidence_df[["GPS Confidence"]].describe().to_csv(statistics_csv)

        figure: Path | None = None
        if self.config.save_figures:
            figure = self.config.figures_dir / f"gps_confidence_{drive}.png"
            self._save_figure(confidence_df, figure, drive)

        return GPSConfidenceArtifacts(
            gps_confidence_csv=gps_confidence_csv,
            sensor_quality_csv=sensor_quality_csv,
            statistics_csv=statistics_csv,
            figure=figure,
        )

    def _save_figure(
        self,
        confidence_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axis = plt.subplots(figsize=(12, 5))
        axis.plot(confidence_df["GPS Confidence"], linewidth=1.8, color="tab:blue")
        axis.set_title(f"GPS Confidence - {drive}")
        axis.set_xlabel("Frame")
        axis.set_ylabel("GPS Confidence")
        axis.set_ylim(0, 1)
        axis.grid(True, alpha=0.3)
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)


def process_gps_confidence_for_drive(
    drive: str,
    results_dir: Path | str,
    figures_dir: Path | str,
    save_figures: bool = True,
) -> pd.DataFrame:
    """Convenience API used by orchestration code for one drive."""

    config = GPSConfidenceConfig(
        results_dir=Path(results_dir),
        figures_dir=Path(figures_dir),
        save_figures=save_figures,
    )
    processor = GPSConfidenceProcessor(config)
    confidence_df, _ = processor.process_drive(drive)
    return confidence_df


def configure_logging(level: int = logging.INFO) -> None:
    """Configure console logging for script execution."""

    logging.basicConfig(
        level=level,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments for GPS-confidence processing."""

    parser = argparse.ArgumentParser(
        description="Compute GPS confidence from sensor quality CSV files."
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path(r"D:\Research\Papers\Paper_2"),
        help="Project root containing results and figures directories.",
    )
    parser.add_argument(
        "--drive",
        action="append",
        dest="drives",
        help="Drive name to process. Repeat for multiple drives.",
    )
    parser.add_argument("--no-figures", action="store_true", help="Skip figure export.")
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    """Run GPS-confidence extraction from the command line."""

    configure_logging()
    args = parse_args(argv)
    try:
        config = GPSConfidenceConfig(
            results_dir=args.project_root / "results",
            figures_dir=args.project_root / "figures",
            save_figures=not args.no_figures,
        )
        processor = GPSConfidenceProcessor(config)
        processor.process_drives(tuple(args.drives or DEFAULT_DRIVES))
    except GPSConfidenceError:
        LOGGER.exception("GPS-confidence processing failed.")
        return 1
    except Exception:
        LOGGER.exception("Unexpected GPS-confidence processing failure.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
