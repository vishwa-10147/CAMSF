"""
Adaptive sensor weight generation for KITTI Raw drives.

This module productionizes Notebook 09. It combines camera, GPS, and IMU
confidence values, estimates temporal stability/reliability, and normalizes the
result into per-frame adaptive sensor weights.
"""

from __future__ import annotations

import argparse
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

import matplotlib.pyplot as plt
import pandas as pd

try:
    from .camera_quality import DEFAULT_DRIVES
except ImportError:  # pragma: no cover - supports direct script execution.
    from camera_quality import DEFAULT_DRIVES


LOGGER = logging.getLogger(__name__)


CONFIDENCE_COLUMNS: tuple[str, ...] = (
    "Camera Confidence",
    "GPS Confidence",
    "IMU Confidence",
)


WEIGHT_COLUMNS: tuple[str, ...] = (
    "Camera Weight",
    "GPS Weight",
    "IMU Weight",
)


@dataclass(frozen=True)
class AdaptiveWeightConfig:
    """Configuration for adaptive-weight generation."""

    results_dir: Path
    figures_dir: Path
    rolling_window: int = 5
    save_figures: bool = True


@dataclass(frozen=True)
class AdaptiveWeightArtifacts:
    """Paths generated by an adaptive-weight processing run."""

    weights_csv: Path
    statistics_csv: Path
    summary_csv: Path
    line_figure: Path | None
    distribution_figure: Path | None


class AdaptiveWeightError(RuntimeError):
    """Raised when adaptive-weight generation cannot complete safely."""


class AdaptiveWeightProcessor:
    """Generate notebook-compatible adaptive sensor weights."""

    def __init__(
        self,
        config: AdaptiveWeightConfig,
        logger: logging.Logger | None = None,
    ) -> None:
        self.config = config
        self.logger = logger or LOGGER

    def process_drive(self, drive: str) -> tuple[pd.DataFrame, AdaptiveWeightArtifacts]:
        """Generate adaptive weights for one KITTI Raw drive."""

        self.logger.info("Starting adaptive weight generation for %s", drive)
        fusion_df = self._load_confidence_dataframe(drive)
        weights_df = self.compute_weights(fusion_df)
        artifacts = self._export_drive_outputs(drive, weights_df)
        self.logger.info(
            "Completed adaptive weights for %s: %s frames -> %s",
            drive,
            len(weights_df),
            artifacts.weights_csv,
        )
        return weights_df, artifacts

    def process_drives(
        self,
        drives: Sequence[str] | None = None,
    ) -> dict[str, AdaptiveWeightArtifacts]:
        """Process multiple drives and return artifact paths keyed by drive."""

        selected_drives = tuple(drives or DEFAULT_DRIVES)
        if not selected_drives:
            raise AdaptiveWeightError("At least one drive must be provided.")

        artifacts_by_drive: dict[str, AdaptiveWeightArtifacts] = {}
        for drive in selected_drives:
            _, artifacts = self.process_drive(drive)
            artifacts_by_drive[drive] = artifacts
        return artifacts_by_drive

    def compute_weights(self, fusion_df: pd.DataFrame) -> pd.DataFrame:
        """Compute temporal stability, reliability, and normalized weights."""

        self._validate_confidence_dataframe(fusion_df)
        result = fusion_df[["Frame", *CONFIDENCE_COLUMNS]].copy()

        for column in CONFIDENCE_COLUMNS:
            stability_column = f"{column} Stability"
            reliability_column = f"{column} Reliability"

            result[stability_column] = (
                result[column]
                .rolling(self.config.rolling_window, min_periods=1)
                .std()
                .fillna(0.0)
            )
            stability = result[stability_column]
            stability_norm = (
                (stability - stability.min())
                / (stability.max() - stability.min() + 1e-8)
            )
            result[reliability_column] = result[column] * (1.0 - stability_norm)

        total_reliability = (
            result["Camera Confidence Reliability"]
            + result["GPS Confidence Reliability"]
            + result["IMU Confidence Reliability"]
        )
        if (total_reliability <= 0).any():
            raise AdaptiveWeightError("Non-positive total reliability encountered.")

        result["Camera Weight"] = result["Camera Confidence Reliability"] / total_reliability
        result["GPS Weight"] = result["GPS Confidence Reliability"] / total_reliability
        result["IMU Weight"] = result["IMU Confidence Reliability"] / total_reliability
        result["Weight Sum"] = result[list(WEIGHT_COLUMNS)].sum(axis=1)
        return result

    def _load_confidence_dataframe(self, drive: str) -> pd.DataFrame:
        camera_csv = self.config.results_dir / f"camera_confidence_{drive}.csv"
        sensor_csv = self.config.results_dir / f"sensor_confidence_index_{drive}.csv"

        if not camera_csv.exists():
            raise AdaptiveWeightError(f"Camera confidence CSV not found: {camera_csv}")
        if not sensor_csv.exists():
            raise AdaptiveWeightError(f"Sensor confidence CSV not found: {sensor_csv}")

        camera_df = pd.read_csv(camera_csv)
        sensor_df = pd.read_csv(sensor_csv)
        required_camera = {"Frame", "Camera Confidence"}
        required_sensor = {"GPS Confidence", "IMU Confidence"}

        if not required_camera.issubset(camera_df.columns):
            raise AdaptiveWeightError(f"Camera confidence CSV missing: {required_camera}")
        if not required_sensor.issubset(sensor_df.columns):
            raise AdaptiveWeightError(f"Sensor confidence CSV missing: {required_sensor}")
        if len(camera_df) != len(sensor_df):
            raise AdaptiveWeightError(
                f"Frame count mismatch for {drive}: camera={len(camera_df)}, "
                f"sensor={len(sensor_df)}"
            )

        return pd.DataFrame(
            {
                "Frame": camera_df["Frame"].astype(int),
                "Camera Confidence": camera_df["Camera Confidence"],
                "GPS Confidence": sensor_df["GPS Confidence"],
                "IMU Confidence": sensor_df["IMU Confidence"],
            }
        )

    def _validate_confidence_dataframe(self, fusion_df: pd.DataFrame) -> None:
        required_columns = ("Frame", *CONFIDENCE_COLUMNS)
        missing = [column for column in required_columns if column not in fusion_df.columns]
        if missing:
            raise AdaptiveWeightError(f"Confidence dataframe is missing columns: {missing}")
        if fusion_df.empty:
            raise AdaptiveWeightError("Confidence dataframe contains no rows.")

    def _export_drive_outputs(
        self,
        drive: str,
        weights_df: pd.DataFrame,
    ) -> AdaptiveWeightArtifacts:
        self.config.results_dir.mkdir(parents=True, exist_ok=True)
        self.config.figures_dir.mkdir(parents=True, exist_ok=True)

        weights_csv = self.config.results_dir / f"adaptive_sensor_weights_{drive}.csv"
        statistics_csv = self.config.results_dir / f"adaptive_weight_statistics_{drive}.csv"
        summary_csv = self.config.results_dir / f"adaptive_weight_summary_{drive}.csv"

        weights_df.to_csv(weights_csv, index=False)
        weights_df[list(WEIGHT_COLUMNS)].describe().to_csv(statistics_csv)
        self._build_summary(weights_df).to_csv(summary_csv, index=False)

        line_figure: Path | None = None
        distribution_figure: Path | None = None
        if self.config.save_figures:
            line_figure = self.config.figures_dir / f"adaptive_sensor_weights_{drive}.png"
            distribution_figure = (
                self.config.figures_dir / f"adaptive_weight_distribution_{drive}.png"
            )
            self._save_line_figure(weights_df, line_figure, drive)
            self._save_distribution_figure(weights_df, distribution_figure, drive)

        return AdaptiveWeightArtifacts(
            weights_csv=weights_csv,
            statistics_csv=statistics_csv,
            summary_csv=summary_csv,
            line_figure=line_figure,
            distribution_figure=distribution_figure,
        )

    def _build_summary(self, weights_df: pd.DataFrame) -> pd.DataFrame:
        return pd.DataFrame(
            {
                "Metric": [
                    "Average Camera Weight",
                    "Average GPS Weight",
                    "Average IMU Weight",
                    "Average Weight Sum",
                ],
                "Value": [
                    float(weights_df["Camera Weight"].mean()),
                    float(weights_df["GPS Weight"].mean()),
                    float(weights_df["IMU Weight"].mean()),
                    float(weights_df["Weight Sum"].mean()),
                ],
            }
        )

    def _save_line_figure(
        self,
        weights_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axis = plt.subplots(figsize=(12, 5))
        for column in WEIGHT_COLUMNS:
            axis.plot(weights_df["Frame"], weights_df[column], linewidth=1.6, label=column)
        axis.set_title(f"Confidence-Driven Adaptive Sensor Weights - {drive}")
        axis.set_xlabel("Frame")
        axis.set_ylabel("Adaptive Weight")
        axis.set_ylim(0, 1)
        axis.grid(True, alpha=0.3)
        axis.legend()
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)

    def _save_distribution_figure(
        self,
        weights_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axis = plt.subplots(figsize=(9, 5))
        axis.hist(
            [weights_df[column] for column in WEIGHT_COLUMNS],
            bins=20,
            label=list(WEIGHT_COLUMNS),
            alpha=0.75,
        )
        axis.set_title(f"Adaptive Weight Distribution - {drive}")
        axis.set_xlabel("Adaptive Weight")
        axis.set_ylabel("Frequency")
        axis.grid(True, axis="y", alpha=0.3)
        axis.legend()
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)


def process_adaptive_weights_for_drive(
    drive: str,
    results_dir: Path | str,
    figures_dir: Path | str,
    rolling_window: int = 5,
    save_figures: bool = True,
) -> pd.DataFrame:
    """Convenience API used by orchestration code for one drive."""

    config = AdaptiveWeightConfig(
        results_dir=Path(results_dir),
        figures_dir=Path(figures_dir),
        rolling_window=rolling_window,
        save_figures=save_figures,
    )
    processor = AdaptiveWeightProcessor(config)
    weights_df, _ = processor.process_drive(drive)
    return weights_df


def configure_logging(level: int = logging.INFO) -> None:
    """Configure console logging for script execution."""

    logging.basicConfig(
        level=level,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments for adaptive-weight processing."""

    parser = argparse.ArgumentParser(
        description="Generate adaptive camera/GPS/IMU weights from confidence CSVs."
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path(r"D:\Research\Papers\Paper_2"),
        help="Project root containing results and figures directories.",
    )
    parser.add_argument(
        "--drive",
        action="append",
        dest="drives",
        help="Drive name to process. Repeat for multiple drives.",
    )
    parser.add_argument("--rolling-window", type=int, default=5)
    parser.add_argument("--no-figures", action="store_true", help="Skip figure export.")
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    """Run adaptive-weight generation from the command line."""

    configure_logging()
    args = parse_args(argv)
    try:
        config = AdaptiveWeightConfig(
            results_dir=args.project_root / "results",
            figures_dir=args.project_root / "figures",
            rolling_window=args.rolling_window,
            save_figures=not args.no_figures,
        )
        processor = AdaptiveWeightProcessor(config)
        processor.process_drives(tuple(args.drives or DEFAULT_DRIVES))
    except AdaptiveWeightError:
        LOGGER.exception("Adaptive-weight generation failed.")
        return 1
    except Exception:
        LOGGER.exception("Unexpected adaptive-weight generation failure.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
