"""
Camera quality extraction for KITTI Raw drives.

This module productionizes the camera-quality stage documented in Notebook 04
without modifying the notebook. It loads every synchronized camera frame for a
KITTI Raw drive, converts the frame to grayscale, computes the same metrics used
in the notebook, and exports drive-specific CSV and figure artifacts.
"""

from __future__ import annotations

import argparse
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

import cv2
import matplotlib.pyplot as plt
import pandas as pd

try:
    from .kitti_raw_dataset import KITTIRawDataset
    from .quality_metrics import CameraQualityMetrics
except ImportError:  # pragma: no cover - supports direct script execution.
    from kitti_raw_dataset import KITTIRawDataset
    from quality_metrics import CameraQualityMetrics


LOGGER = logging.getLogger(__name__)


DEFAULT_DRIVES: tuple[str, ...] = (
    "2011_09_26_drive_0001_sync",
    "2011_09_26_drive_0002_sync",
    "2011_09_26_drive_0005_sync",
    "2011_09_26_drive_0009_sync",
    "2011_09_26_drive_0011_sync",
    "2011_09_26_drive_0015_sync",
    "2011_09_26_drive_0018_sync",
    "2011_09_26_drive_0020_sync",
    "2011_09_26_drive_0022_sync",
)


QUALITY_COLUMNS: tuple[str, ...] = (
    "Brightness",
    "Contrast",
    "Blur",
    "Entropy",
    "Dynamic Range",
    "Edge Density",
    "Noise",
    "Frame",
)


@dataclass(frozen=True)
class CameraQualityConfig:
    """Configuration for a camera-quality processing run."""

    dataset_root: Path
    results_dir: Path
    figures_dir: Path
    image_camera: str = "image_02"
    save_figures: bool = True


@dataclass(frozen=True)
class CameraQualityArtifacts:
    """Paths generated by a camera-quality processing run."""

    metrics_csv: Path
    statistics_csv: Path
    trend_figure: Path | None
    correlation_figure: Path | None


class CameraQualityError(RuntimeError):
    """Raised when camera-quality processing cannot complete safely."""


class CameraQualityProcessor:
    """Compute and export notebook-compatible camera-quality metrics."""

    def __init__(
        self,
        config: CameraQualityConfig,
        metric_calculator: CameraQualityMetrics | None = None,
        logger: logging.Logger | None = None,
    ) -> None:
        self.config = config
        self.metric_calculator = metric_calculator or CameraQualityMetrics()
        self.logger = logger or LOGGER

    def process_drive(self, drive: str) -> tuple[pd.DataFrame, CameraQualityArtifacts]:
        """
        Process one KITTI Raw drive and export metrics, statistics, and figures.

        Parameters
        ----------
        drive:
            KITTI Raw synchronized drive name, for example
            ``2011_09_26_drive_0001_sync``.

        Returns
        -------
        tuple[pandas.DataFrame, CameraQualityArtifacts]
            The computed frame-level metrics and the artifact paths written.
        """

        self.logger.info("Starting camera quality processing for %s", drive)
        dataset = KITTIRawDataset(self.config.dataset_root, drive)
        self._validate_dataset(dataset)

        frame_count = dataset.get_frame_count()
        if frame_count <= 0:
            raise CameraQualityError(f"No camera frames found for drive: {drive}")

        records: list[dict[str, float | int]] = []
        for frame in range(frame_count):
            try:
                image_rgb = dataset.load_image(frame)
                gray = cv2.cvtColor(image_rgb, cv2.COLOR_RGB2GRAY)
                metrics = self.metric_calculator.compute(gray)
                metrics["Frame"] = frame
                records.append(metrics)
            except Exception as exc:
                raise CameraQualityError(
                    f"Failed to compute camera-quality metrics for {drive}, "
                    f"frame {frame}."
                ) from exc

            if frame and frame % 250 == 0:
                self.logger.info(
                    "Processed %s camera-quality frames for %s",
                    frame,
                    drive,
                )

        quality_df = pd.DataFrame.from_records(records, columns=QUALITY_COLUMNS)
        artifacts = self._export_drive_outputs(drive, quality_df)
        self.logger.info(
            "Completed camera quality for %s: %s frames -> %s",
            drive,
            len(quality_df),
            artifacts.metrics_csv,
        )
        return quality_df, artifacts

    def process_drives(
        self,
        drives: Sequence[str] | None = None,
    ) -> dict[str, CameraQualityArtifacts]:
        """Process multiple drives and return artifact paths keyed by drive."""

        selected_drives = tuple(drives or DEFAULT_DRIVES)
        if not selected_drives:
            raise CameraQualityError("At least one drive must be provided.")

        artifacts_by_drive: dict[str, CameraQualityArtifacts] = {}
        for drive in selected_drives:
            _, artifacts = self.process_drive(drive)
            artifacts_by_drive[drive] = artifacts
        return artifacts_by_drive

    def _validate_dataset(self, dataset: KITTIRawDataset) -> None:
        required_paths = {
            "drive": dataset.drive_path,
            "camera images": dataset.image_dir,
            "OXTS": dataset.oxts_dir,
            "camera calibration": dataset.calib_cam,
        }
        missing = [name for name, path in required_paths.items() if not path.exists()]
        if missing:
            details = ", ".join(missing)
            raise CameraQualityError(
                f"Missing required KITTI data for {dataset.drive}: {details}"
            )

    def _export_drive_outputs(
        self,
        drive: str,
        quality_df: pd.DataFrame,
    ) -> CameraQualityArtifacts:
        self.config.results_dir.mkdir(parents=True, exist_ok=True)
        self.config.figures_dir.mkdir(parents=True, exist_ok=True)

        metrics_csv = self.config.results_dir / f"camera_quality_metrics_{drive}.csv"
        statistics_csv = self.config.results_dir / f"camera_quality_statistics_{drive}.csv"
        quality_df.to_csv(metrics_csv, index=False)
        quality_df.describe().to_csv(statistics_csv)

        trend_figure: Path | None = None
        correlation_figure: Path | None = None
        if self.config.save_figures:
            trend_figure = (
                self.config.figures_dir / f"camera_quality_trends_{drive}.png"
            )
            correlation_figure = (
                self.config.figures_dir / f"camera_quality_correlation_{drive}.png"
            )
            self._save_trend_figure(quality_df, trend_figure, drive)
            self._save_correlation_figure(quality_df, correlation_figure, drive)

        return CameraQualityArtifacts(
            metrics_csv=metrics_csv,
            statistics_csv=statistics_csv,
            trend_figure=trend_figure,
            correlation_figure=correlation_figure,
        )

    def _save_trend_figure(
        self,
        quality_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axes = plt.subplots(3, 1, figsize=(12, 10), sharex=True)
        plot_columns = ("Brightness", "Blur", "Entropy")
        colors = ("tab:blue", "tab:orange", "tab:green")

        for axis, column, color in zip(axes, plot_columns, colors):
            axis.plot(quality_df["Frame"], quality_df[column], color=color, linewidth=1.6)
            axis.set_ylabel(column)
            axis.grid(True, alpha=0.3)

        axes[-1].set_xlabel("Frame")
        fig.suptitle(f"Camera Quality Trends - {drive}")
        fig.tight_layout(rect=(0, 0, 1, 0.97))
        fig.savefig(output_path, dpi=300)
        plt.close(fig)

    def _save_correlation_figure(
        self,
        quality_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        correlation = quality_df.drop(columns=["Frame"]).corr()
        fig, axis = plt.subplots(figsize=(9, 7))
        image = axis.imshow(correlation, cmap="coolwarm", vmin=-1, vmax=1)
        axis.set_title(f"Camera Quality Correlation - {drive}")
        axis.set_xticks(range(len(correlation.columns)))
        axis.set_yticks(range(len(correlation.index)))
        axis.set_xticklabels(correlation.columns, rotation=45, ha="right")
        axis.set_yticklabels(correlation.index)
        fig.colorbar(image, ax=axis, fraction=0.046, pad=0.04)
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)


def discover_kitti_drives(dataset_root: Path, date: str = "2011_09_26") -> tuple[str, ...]:
    """Return available KITTI Raw synchronized drive names for a date folder."""

    date_dir = dataset_root / date
    if not date_dir.exists():
        raise CameraQualityError(f"KITTI date directory not found: {date_dir}")

    drives = sorted(path.name for path in date_dir.glob("*_drive_*_sync") if path.is_dir())
    if not drives:
        raise CameraQualityError(f"No synchronized KITTI drives found in {date_dir}")
    return tuple(drives)


def process_camera_quality_for_drive(
    dataset_root: Path | str,
    drive: str,
    results_dir: Path | str,
    figures_dir: Path | str,
    save_figures: bool = True,
) -> pd.DataFrame:
    """Convenience API used by orchestration code for one drive."""

    config = CameraQualityConfig(
        dataset_root=Path(dataset_root),
        results_dir=Path(results_dir),
        figures_dir=Path(figures_dir),
        save_figures=save_figures,
    )
    processor = CameraQualityProcessor(config)
    quality_df, _ = processor.process_drive(drive)
    return quality_df


def configure_logging(level: int = logging.INFO) -> None:
    """Configure console logging for script execution."""

    logging.basicConfig(
        level=level,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments for camera-quality batch processing."""

    parser = argparse.ArgumentParser(
        description="Compute camera-quality metrics for KITTI Raw drives."
    )
    parser.add_argument(
        "--dataset-root",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "datasets" / "KITTI",
        help="Path to KITTI Raw dataset root.",
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="Project root containing results and figures directories.",
    )
    parser.add_argument(
        "--drive",
        action="append",
        dest="drives",
        help="Drive name to process. Repeat for multiple drives.",
    )
    parser.add_argument(
        "--all-discovered",
        action="store_true",
        help="Process every synchronized drive found under the dataset date folder.",
    )
    parser.add_argument(
        "--no-figures",
        action="store_true",
        help="Skip figure export.",
    )
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    """Run camera-quality extraction from the command line."""

    configure_logging()
    args = parse_args(argv)

    try:
        drives = (
            discover_kitti_drives(args.dataset_root)
            if args.all_discovered
            else tuple(args.drives or DEFAULT_DRIVES)
        )
        config = CameraQualityConfig(
            dataset_root=args.dataset_root,
            results_dir=args.project_root / "results",
            figures_dir=args.project_root / "figures",
            save_figures=not args.no_figures,
        )
        processor = CameraQualityProcessor(config)
        processor.process_drives(drives)
    except CameraQualityError:
        LOGGER.exception("Camera-quality processing failed.")
        return 1
    except Exception:
        LOGGER.exception("Unexpected camera-quality processing failure.")
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
