"""
IMU quality metric extraction for KITTI Raw drives.

This module productionizes the IMU portion of Notebook 07. It computes motion
smoothness and angular stability from KITTI OXTS acceleration and angular-rate
channels, then updates the combined sensor-quality CSV used downstream.
"""

from __future__ import annotations

import argparse
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

try:
    from .camera_quality import DEFAULT_DRIVES
    from .gps_quality import GPSQualityProcessor, GPSQualityConfig, OXTS_COLUMNS
except ImportError:  # pragma: no cover - supports direct script execution.
    from camera_quality import DEFAULT_DRIVES
    from gps_quality import GPSQualityProcessor, GPSQualityConfig, OXTS_COLUMNS


LOGGER = logging.getLogger(__name__)


IMU_QUALITY_COLUMNS: tuple[str, ...] = (
    "Motion Smoothness",
    "Angular Stability",
)


@dataclass(frozen=True)
class IMUQualityConfig:
    """Configuration for IMU-quality processing."""

    dataset_root: Path
    results_dir: Path
    figures_dir: Path
    save_figures: bool = True


@dataclass(frozen=True)
class IMUQualityArtifacts:
    """Paths generated by an IMU-quality processing run."""

    imu_quality_csv: Path
    sensor_quality_csv: Path
    summary_csv: Path
    imu_figure: Path | None


class IMUQualityError(RuntimeError):
    """Raised when IMU-quality processing cannot complete safely."""


class IMUQualityProcessor:
    """Compute notebook-compatible IMU quality metrics for KITTI Raw drives."""

    def __init__(
        self,
        config: IMUQualityConfig,
        logger: logging.Logger | None = None,
    ) -> None:
        self.config = config
        self.logger = logger or LOGGER

    def process_drive(self, drive: str) -> tuple[pd.DataFrame, IMUQualityArtifacts]:
        """Compute IMU quality for one drive and update combined sensor-quality output."""

        self.logger.info("Starting IMU quality processing for %s", drive)
        base_df = self._load_or_create_base_dataframe(drive)
        quality_df = self.compute_quality(base_df)
        artifacts = self._export_drive_outputs(drive, quality_df)
        self.logger.info(
            "Completed IMU quality for %s: %s frames -> %s",
            drive,
            len(quality_df),
            artifacts.imu_quality_csv,
        )
        return quality_df, artifacts

    def process_drives(
        self,
        drives: Sequence[str] | None = None,
    ) -> dict[str, IMUQualityArtifacts]:
        """Process multiple drives and return artifact paths keyed by drive."""

        selected_drives = tuple(drives or DEFAULT_DRIVES)
        if not selected_drives:
            raise IMUQualityError("At least one drive must be provided.")

        artifacts_by_drive: dict[str, IMUQualityArtifacts] = {}
        for drive in selected_drives:
            _, artifacts = self.process_drive(drive)
            artifacts_by_drive[drive] = artifacts
        return artifacts_by_drive

    def compute_quality(self, sensor_df: pd.DataFrame) -> pd.DataFrame:
        """Compute IMU motion smoothness and angular stability."""

        self._validate_input_dataframe(sensor_df)
        quality_df = sensor_df.copy()

        acceleration = np.sqrt(
            quality_df["ax"].to_numpy(dtype=float) ** 2
            + quality_df["ay"].to_numpy(dtype=float) ** 2
            + quality_df["az"].to_numpy(dtype=float) ** 2
        )
        motion_change = self._first_order_abs_change(acceleration)
        quality_df["Motion Smoothness"] = 1.0 / (1.0 + motion_change)

        angular_rate = np.sqrt(
            quality_df["wx"].to_numpy(dtype=float) ** 2
            + quality_df["wy"].to_numpy(dtype=float) ** 2
            + quality_df["wz"].to_numpy(dtype=float) ** 2
        )
        angular_change = self._first_order_abs_change(angular_rate)
        quality_df["Angular Stability"] = 1.0 / (1.0 + angular_change)
        return quality_df

    def _load_or_create_base_dataframe(self, drive: str) -> pd.DataFrame:
        sensor_quality_csv = (
            self.config.results_dir / f"sensor_quality_metrics_{drive}.csv"
        )
        oxts_csv = self.config.results_dir / f"oxts_dataframe_{drive}.csv"

        if sensor_quality_csv.exists():
            return pd.read_csv(sensor_quality_csv)
        if oxts_csv.exists():
            return pd.read_csv(oxts_csv)

        self.logger.info(
            "No OXTS-derived CSV found for %s; running GPS/OXTS loader first.",
            drive,
        )
        gps_config = GPSQualityConfig(
            dataset_root=self.config.dataset_root,
            results_dir=self.config.results_dir,
            figures_dir=self.config.figures_dir,
            save_figures=False,
        )
        gps_processor = GPSQualityProcessor(gps_config, logger=self.logger)
        gps_df, _ = gps_processor.process_drive(drive)
        return gps_df

    def _validate_input_dataframe(self, sensor_df: pd.DataFrame) -> None:
        missing = [column for column in OXTS_COLUMNS if column not in sensor_df.columns]
        if missing:
            raise IMUQualityError(f"Input dataframe is missing OXTS columns: {missing}")
        if sensor_df.empty:
            raise IMUQualityError("Input dataframe contains no rows.")

    def _first_order_abs_change(self, values: np.ndarray) -> np.ndarray:
        if len(values) == 1:
            return np.array([0.0], dtype=float)
        change = np.abs(np.diff(values))
        return np.insert(change, 0, change[0])

    def _export_drive_outputs(
        self,
        drive: str,
        quality_df: pd.DataFrame,
    ) -> IMUQualityArtifacts:
        self.config.results_dir.mkdir(parents=True, exist_ok=True)
        self.config.figures_dir.mkdir(parents=True, exist_ok=True)

        imu_quality_csv = self.config.results_dir / f"imu_quality_metrics_{drive}.csv"
        sensor_quality_csv = (
            self.config.results_dir / f"sensor_quality_metrics_{drive}.csv"
        )
        summary_csv = self.config.results_dir / f"imu_quality_summary_{drive}.csv"

        quality_df[list(IMU_QUALITY_COLUMNS)].to_csv(imu_quality_csv, index=False)
        quality_df.to_csv(sensor_quality_csv, index=False)
        self._build_summary(quality_df).to_csv(summary_csv, index=False)

        imu_figure: Path | None = None
        if self.config.save_figures:
            imu_figure = self.config.figures_dir / f"imu_quality_{drive}.png"
            self._save_imu_figure(quality_df, imu_figure, drive)

        return IMUQualityArtifacts(
            imu_quality_csv=imu_quality_csv,
            sensor_quality_csv=sensor_quality_csv,
            summary_csv=summary_csv,
            imu_figure=imu_figure,
        )

    def _build_summary(self, quality_df: pd.DataFrame) -> pd.DataFrame:
        return pd.DataFrame(
            {
                "Metric": list(IMU_QUALITY_COLUMNS),
                "Average": [float(quality_df[column].mean()) for column in IMU_QUALITY_COLUMNS],
            }
        )

    def _save_imu_figure(
        self,
        quality_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axis = plt.subplots(figsize=(12, 5))
        axis.plot(
            quality_df["Motion Smoothness"],
            label="Motion Smoothness",
            linewidth=1.8,
        )
        axis.plot(
            quality_df["Angular Stability"],
            label="Angular Stability",
            linewidth=1.8,
        )
        axis.set_title(f"IMU Quality Metrics - {drive}")
        axis.set_xlabel("Frame")
        axis.set_ylabel("Quality Score")
        axis.set_ylim(0, 1.05)
        axis.grid(True, alpha=0.3)
        axis.legend()
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)


def process_imu_quality_for_drive(
    dataset_root: Path | str,
    drive: str,
    results_dir: Path | str,
    figures_dir: Path | str,
    save_figures: bool = True,
) -> pd.DataFrame:
    """Convenience API used by orchestration code for one drive."""

    config = IMUQualityConfig(
        dataset_root=Path(dataset_root),
        results_dir=Path(results_dir),
        figures_dir=Path(figures_dir),
        save_figures=save_figures,
    )
    processor = IMUQualityProcessor(config)
    quality_df, _ = processor.process_drive(drive)
    return quality_df


def configure_logging(level: int = logging.INFO) -> None:
    """Configure console logging for script execution."""

    logging.basicConfig(
        level=level,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments for IMU-quality processing."""

    parser = argparse.ArgumentParser(
        description="Compute IMU quality metrics from KITTI Raw OXTS packets."
    )
    parser.add_argument(
        "--dataset-root",
        type=Path,
        default=Path(r"D:\Research\Datasets\KITTI"),
        help="Path to KITTI Raw dataset root.",
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path(r"D:\Research\Papers\Paper_2"),
        help="Project root containing results and figures directories.",
    )
    parser.add_argument(
        "--drive",
        action="append",
        dest="drives",
        help="Drive name to process. Repeat for multiple drives.",
    )
    parser.add_argument("--no-figures", action="store_true", help="Skip figure export.")
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    """Run IMU-quality extraction from the command line."""

    configure_logging()
    args = parse_args(argv)
    try:
        config = IMUQualityConfig(
            dataset_root=args.dataset_root,
            results_dir=args.project_root / "results",
            figures_dir=args.project_root / "figures",
            save_figures=not args.no_figures,
        )
        processor = IMUQualityProcessor(config)
        processor.process_drives(tuple(args.drives or DEFAULT_DRIVES))
    except IMUQualityError:
        LOGGER.exception("IMU-quality processing failed.")
        return 1
    except Exception:
        LOGGER.exception("Unexpected IMU-quality processing failure.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
