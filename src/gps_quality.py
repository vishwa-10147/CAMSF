"""
GPS quality metric extraction for KITTI Raw drives.

This module productionizes the GPS portion of Notebook 07. It loads KITTI OXTS
packets for a drive, computes the notebook GPS quality metrics for every frame,
and exports drive-specific CSV artifacts for downstream confidence estimation.
"""

from __future__ import annotations

import argparse
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Sequence

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

try:
    from .camera_quality import DEFAULT_DRIVES
    from .kitti_raw_dataset import KITTIRawDataset
except ImportError:  # pragma: no cover - supports direct script execution.
    from camera_quality import DEFAULT_DRIVES
    from kitti_raw_dataset import KITTIRawDataset


LOGGER = logging.getLogger(__name__)
EARTH_RADIUS_METERS = 6_371_000.0


OXTS_COLUMNS: tuple[str, ...] = (
    "lat",
    "lon",
    "alt",
    "roll",
    "pitch",
    "yaw",
    "vn",
    "ve",
    "vf",
    "vl",
    "vu",
    "ax",
    "ay",
    "az",
    "af",
    "al",
    "au",
    "wx",
    "wy",
    "wz",
    "wf",
    "wl",
    "wu",
    "pos_accuracy",
    "vel_accuracy",
    "navstat",
    "numsats",
    "posmode",
    "velmode",
    "orimode",
)


GPS_QUALITY_COLUMNS: tuple[str, ...] = (
    "GPS Distance (m)",
    "GPS Position Stability",
    "GPS Velocity Stability",
    "GPS Heading Stability",
    "Satellite Quality",
    "Position Accuracy Score",
    "Velocity Accuracy Score",
)


@dataclass(frozen=True)
class GPSQualityConfig:
    """Configuration for GPS-quality processing."""

    dataset_root: Path
    results_dir: Path
    figures_dir: Path
    save_figures: bool = True


@dataclass(frozen=True)
class GPSQualityArtifacts:
    """Paths generated by a GPS-quality processing run."""

    oxts_csv: Path
    gps_quality_csv: Path
    sensor_quality_csv: Path
    summary_csv: Path
    distance_figure: Path | None


class GPSQualityError(RuntimeError):
    """Raised when GPS-quality processing cannot complete safely."""


class GPSQualityProcessor:
    """Compute notebook-compatible GPS quality metrics for KITTI Raw drives."""

    def __init__(
        self,
        config: GPSQualityConfig,
        logger: logging.Logger | None = None,
    ) -> None:
        self.config = config
        self.logger = logger or LOGGER

    def process_drive(self, drive: str) -> tuple[pd.DataFrame, GPSQualityArtifacts]:
        """Load one drive's OXTS packets, compute GPS quality, and export artifacts."""

        self.logger.info("Starting GPS quality processing for %s", drive)
        dataset = KITTIRawDataset(self.config.dataset_root, drive)
        self._validate_dataset(dataset)

        oxts_df = self.load_oxts_dataframe(dataset)
        quality_df = self.compute_quality(oxts_df)
        artifacts = self._export_drive_outputs(drive, quality_df)

        self.logger.info(
            "Completed GPS quality for %s: %s frames -> %s",
            drive,
            len(quality_df),
            artifacts.gps_quality_csv,
        )
        return quality_df, artifacts

    def process_drives(
        self,
        drives: Sequence[str] | None = None,
    ) -> dict[str, GPSQualityArtifacts]:
        """Process multiple drives and return artifact paths keyed by drive."""

        selected_drives = tuple(drives or DEFAULT_DRIVES)
        if not selected_drives:
            raise GPSQualityError("At least one drive must be provided.")

        artifacts_by_drive: dict[str, GPSQualityArtifacts] = {}
        for drive in selected_drives:
            _, artifacts = self.process_drive(drive)
            artifacts_by_drive[drive] = artifacts
        return artifacts_by_drive

    def load_oxts_dataframe(self, dataset: KITTIRawDataset) -> pd.DataFrame:
        """
        Load all OXTS packets for a KITTI drive into a typed dataframe.

        The fixed pipeline feeds a *degraded* OXTS frame (written by
        ``gps_degradation.py`` as ``degraded_oxts_<drive>.csv``) into the
        quality stage so that GPS confidence actually reflects the injected
        degradation.  If that artifact is present it takes precedence; only
        when it is absent (fresh clone / pristine run) are the raw KITTI
        packets used.
        """

        degraded_csv = self.config.results_dir / f"degraded_oxts_{dataset.drive}.csv"
        if degraded_csv.exists():
            self.logger.info(
                "Loading degraded OXTS for %s from %s", dataset.drive, degraded_csv
            )
            degraded_df = pd.read_csv(degraded_csv)
            missing = [c for c in OXTS_COLUMNS if c not in degraded_df.columns]
            if missing:
                raise GPSQualityError(
                    f"Degraded OXTS CSV is missing columns: {missing}"
                )
            return degraded_df[list(OXTS_COLUMNS)].reset_index(drop=True)

        frame_count = dataset.get_frame_count()
        if frame_count <= 0:
            raise GPSQualityError(f"No synchronized frames found for {dataset.drive}")

        rows: list[np.ndarray] = []
        for frame in range(frame_count):
            try:
                values = np.asarray(dataset.load_oxts(frame), dtype=float)
            except Exception as exc:
                raise GPSQualityError(
                    f"Failed to load OXTS packet for {dataset.drive}, frame {frame}."
                ) from exc
            if values.shape[0] != len(OXTS_COLUMNS):
                raise GPSQualityError(
                    f"Unexpected OXTS column count for {dataset.drive}, frame {frame}: "
                    f"{values.shape[0]} != {len(OXTS_COLUMNS)}"
                )
            rows.append(values)

        return pd.DataFrame(rows, columns=OXTS_COLUMNS)

    def compute_quality(self, oxts_df: pd.DataFrame) -> pd.DataFrame:
        """Compute the GPS quality metrics used by Notebook 07."""

        self._validate_oxts_dataframe(oxts_df)
        quality_df = oxts_df.copy()

        gps_distance = self._haversine_distance(
            quality_df["lat"].to_numpy(dtype=float),
            quality_df["lon"].to_numpy(dtype=float),
        )
        quality_df["GPS Distance (m)"] = gps_distance
        mean_distance = max(float(np.mean(gps_distance)), 1e-8)
        quality_df["GPS Position Stability"] = np.exp(-gps_distance / mean_distance)

        speed = np.sqrt(
            quality_df["vn"].to_numpy(dtype=float) ** 2
            + quality_df["ve"].to_numpy(dtype=float) ** 2
            + quality_df["vu"].to_numpy(dtype=float) ** 2
        )
        velocity_change = self._first_order_abs_change(speed)
        quality_df["GPS Velocity Stability"] = 1.0 / (1.0 + velocity_change)

        heading_change = self._first_order_abs_change(
            quality_df["yaw"].to_numpy(dtype=float)
        )
        quality_df["GPS Heading Stability"] = 1.0 / (1.0 + heading_change)

        max_satellites = max(float(quality_df["numsats"].max()), 1e-8)
        quality_df["Satellite Quality"] = quality_df["numsats"] / max_satellites

        quality_df["Position Accuracy Score"] = self._inverse_minmax_score(
            quality_df["pos_accuracy"]
        )
        quality_df["Velocity Accuracy Score"] = self._robust_velocity_accuracy_score(
            quality_df["vel_accuracy"]
        )

        return quality_df

    def _validate_dataset(self, dataset: KITTIRawDataset) -> None:
        required_paths = {
            "drive": dataset.drive_path,
            "images": dataset.image_dir,
            "OXTS": dataset.oxts_dir,
        }
        missing = [name for name, path in required_paths.items() if not path.exists()]
        if missing:
            raise GPSQualityError(
                f"Missing required KITTI data for {dataset.drive}: {', '.join(missing)}"
            )

    def _validate_oxts_dataframe(self, oxts_df: pd.DataFrame) -> None:
        missing = [column for column in OXTS_COLUMNS if column not in oxts_df.columns]
        if missing:
            raise GPSQualityError(f"OXTS dataframe is missing columns: {missing}")
        if oxts_df.empty:
            raise GPSQualityError("OXTS dataframe contains no rows.")

    def _haversine_distance(self, lat_deg: np.ndarray, lon_deg: np.ndarray) -> np.ndarray:
        if len(lat_deg) == 1:
            return np.array([0.0], dtype=float)

        lat = np.radians(lat_deg)
        lon = np.radians(lon_deg)
        dlat = np.diff(lat)
        dlon = np.diff(lon)
        a = (
            np.sin(dlat / 2.0) ** 2
            + np.cos(lat[:-1]) * np.cos(lat[1:]) * np.sin(dlon / 2.0) ** 2
        )
        c = 2.0 * np.arctan2(np.sqrt(a), np.sqrt(1.0 - a))
        distance = EARTH_RADIUS_METERS * c
        return np.insert(distance, 0, distance[0])

    def _first_order_abs_change(self, values: np.ndarray) -> np.ndarray:
        if len(values) == 1:
            return np.array([0.0], dtype=float)
        change = np.abs(np.diff(values))
        return np.insert(change, 0, change[0])

    def _inverse_minmax_score(self, values: pd.Series) -> pd.Series:
        minimum = float(values.min())
        maximum = float(values.max())
        span = maximum - minimum
        if span <= 1e-12:
            return pd.Series(np.ones(len(values)), index=values.index)
        return 1.0 - ((values - minimum) / span)

    def _robust_velocity_accuracy_score(self, values: pd.Series) -> pd.Series:
        median = float(values.median())
        mad = float(np.median(np.abs(values - median)))
        mad = max(mad, 1e-6)
        return np.exp(-np.abs(values - median) / (3.0 * mad))

    def _export_drive_outputs(
        self,
        drive: str,
        quality_df: pd.DataFrame,
    ) -> GPSQualityArtifacts:
        self.config.results_dir.mkdir(parents=True, exist_ok=True)
        self.config.figures_dir.mkdir(parents=True, exist_ok=True)

        oxts_csv = self.config.results_dir / f"oxts_dataframe_{drive}.csv"
        gps_quality_csv = self.config.results_dir / f"gps_quality_metrics_{drive}.csv"
        sensor_quality_csv = (
            self.config.results_dir / f"sensor_quality_metrics_{drive}.csv"
        )
        summary_csv = self.config.results_dir / f"gps_quality_summary_{drive}.csv"

        quality_df[list(OXTS_COLUMNS)].to_csv(oxts_csv, index=False)
        quality_df[list(GPS_QUALITY_COLUMNS)].to_csv(gps_quality_csv, index=False)
        quality_df.to_csv(sensor_quality_csv, index=False)
        self._build_summary(quality_df).to_csv(summary_csv, index=False)

        distance_figure: Path | None = None
        if self.config.save_figures:
            distance_figure = self.config.figures_dir / f"gps_distance_{drive}.png"
            self._save_distance_figure(quality_df, distance_figure, drive)

        return GPSQualityArtifacts(
            oxts_csv=oxts_csv,
            gps_quality_csv=gps_quality_csv,
            sensor_quality_csv=sensor_quality_csv,
            summary_csv=summary_csv,
            distance_figure=distance_figure,
        )

    def _build_summary(self, quality_df: pd.DataFrame) -> pd.DataFrame:
        return pd.DataFrame(
            {
                "Metric": list(GPS_QUALITY_COLUMNS),
                "Average": [float(quality_df[column].mean()) for column in GPS_QUALITY_COLUMNS],
            }
        )

    def _save_distance_figure(
        self,
        quality_df: pd.DataFrame,
        output_path: Path,
        drive: str,
    ) -> None:
        fig, axis = plt.subplots(figsize=(12, 5))
        axis.plot(quality_df["GPS Distance (m)"], linewidth=1.8, color="tab:blue")
        axis.set_title(f"GPS Distance Between Consecutive Frames - {drive}")
        axis.set_xlabel("Frame")
        axis.set_ylabel("Distance (meters)")
        axis.grid(True, alpha=0.3)
        fig.tight_layout()
        fig.savefig(output_path, dpi=300)
        plt.close(fig)


def process_gps_quality_for_drive(
    dataset_root: Path | str,
    drive: str,
    results_dir: Path | str,
    figures_dir: Path | str,
    save_figures: bool = True,
) -> pd.DataFrame:
    """Convenience API used by orchestration code for one drive."""

    config = GPSQualityConfig(
        dataset_root=Path(dataset_root),
        results_dir=Path(results_dir),
        figures_dir=Path(figures_dir),
        save_figures=save_figures,
    )
    processor = GPSQualityProcessor(config)
    quality_df, _ = processor.process_drive(drive)
    return quality_df


def configure_logging(level: int = logging.INFO) -> None:
    """Configure console logging for script execution."""

    logging.basicConfig(
        level=level,
        format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",
    )


def parse_args(argv: Iterable[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments for GPS-quality processing."""

    parser = argparse.ArgumentParser(
        description="Compute GPS quality metrics from KITTI Raw OXTS packets."
    )
    parser.add_argument(
        "--dataset-root",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "datasets" / "KITTI",
        help="Path to KITTI Raw dataset root.",
    )
    parser.add_argument(
        "--project-root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="Project root containing results and figures directories.",
    )
    parser.add_argument(
        "--drive",
        action="append",
        dest="drives",
        help="Drive name to process. Repeat for multiple drives.",
    )
    parser.add_argument("--no-figures", action="store_true", help="Skip figure export.")
    return parser.parse_args(argv)


def main(argv: Iterable[str] | None = None) -> int:
    """Run GPS-quality extraction from the command line."""

    configure_logging()
    args = parse_args(argv)
    try:
        config = GPSQualityConfig(
            dataset_root=args.dataset_root,
            results_dir=args.project_root / "results",
            figures_dir=args.project_root / "figures",
            save_figures=not args.no_figures,
        )
        processor = GPSQualityProcessor(config)
        processor.process_drives(tuple(args.drives or DEFAULT_DRIVES))
    except GPSQualityError:
        LOGGER.exception("GPS-quality processing failed.")
        return 1
    except Exception:
        LOGGER.exception("Unexpected GPS-quality processing failure.")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
